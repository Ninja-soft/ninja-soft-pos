// Catálogo de bancos, billeteras, fintechs y exchanges cripto de Argentina
// para el medio de pago "Transferencia": el comercio elige dónde recibe las
// transferencias y el POS muestra el logo, el CBU/CVU y el alias.
//
// Logos en public/images/banks (mismas convenciones que logos.ts): WebP
// transparente, recortado al contenido, sin placa blanca.
//   <slug>-icon.webp      → isotipo cuadrado 256x256 (ícono de app cuando la
//                           marca no tiene isotipo suelto: iconFullBleed).
//   <slug>-wordmark.webp  → logo horizontal (alto máx. 96 px).
//   *-on-dark.webp        → variante para fondo oscuro, solo si el logo es
//                           oscuro y no se leería sobre el tema ninja-dark.
// `fallback: true` = no se encontró logo oficial: monograma neutro, no un
// logo inventado.
//
// Códigos:
//   bcraCodes → código de entidad BCRA = primeros 3 dígitos del CBU.
//   cvuPsp    → código del PSP en el CVU (dígitos 4 a 7; el CVU arranca con
//               "000" y el 8.º dígito es verificador). Solo se cargan los
//               confirmados; el resto queda vacío.
// Un mismo código nunca apunta a dos entidades: si una marca opera sobre el
// código de otra (Cuenta DNI sobre Banco Provincia 014, Ualá Bank sobre el
// ex Wilobank 384), el código queda en la entidad titular.
//
// Fuentes:
//   - BCRA, API pública "Cheques" (api.bcra.gob.ar/cheques/v1.0/entidades):
//     código y denominación de cada banco.
//   - BCRA, Comunicación "B" 12835 (02/07/2024), anexo de cuentas corrientes
//     en el BCRA (número de cuenta 80 + código de entidad): agrega Brubank
//     143, Open Bank 158, Wilobank 384 (cuenta 93384), Banco Voii 312, Banco
//     de Servicios Financieros 332, Compañía Financiera Argentina 477, Naranja
//     Digital 530 y Reba 572, entre otras.
//     https://www.bcra.gob.ar/Pdfs/comytexord/B12835.pdf
//   - Prefijos de CVU: Mercado Pago 0000003 (PSP 0003), Ualá 0000007 (0007),
//     Prex 0000013 (0013), Bamba 0000120 (0120), AstroPay 0000177 (0177) y
//     DolarApp/ARQ 0000069 (0069), según la tabla de https://servidos.ar/verificador-cbu,
//     verificados con el dígito verificador del primer bloque del CVU.
//   - Logos: sitio oficial de cada marca, ícono oficial de su app en Google
//     Play y Wikimedia Commons (ver el informe de la tarea para el detalle).

