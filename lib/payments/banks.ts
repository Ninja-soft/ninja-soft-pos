const BASE = "/images/banks";

export const BANKS: readonly BankEntity[] = [...ENTRIES].sort((a, b) =>
  a.shortName.localeCompare(b.shortName, "es"),
);

const BY_SLUG = new Map(BANKS.map((b) => [b.slug, b]));
const BY_BCRA = new Map(
  BANKS.flatMap((b) => b.bcraCodes.map((c) => [c, b] as const)),
);
const BY_PSP = new Map(
  BANKS.flatMap((b) => b.cvuPsp.map((c) => [c, b] as const)),
);

export function bankBySlug(slug: string | null | undefined): BankEntity | null {
  return slug ? (BY_SLUG.get(slug) ?? null) : null;
}

export function bankIcon(slug: string, opts?: LogoOpts): string | null {
  const b = BY_SLUG.get(slug);
  if (!b) return null;
  const dark = opts?.on === "dark" && b.iconOnDark ? "-on-dark" : "";
  return `${BASE}/${b.slug}-icon${dark}.webp`;
}

export function bankWordmark(slug: string, opts?: LogoOpts): string | null {
  const b = BY_SLUG.get(slug);
  if (!b) return null;
  const dark = opts?.on === "dark" && b.wordmarkOnDark ? "-on-dark" : "";
  return `${BASE}/${b.slug}-wordmark${dark}.webp`;
}

// Código de entidad BCRA (3 dígitos, primeros del CBU).
export function bankByBcraCode(code: string): BankEntity | null {
  return BY_BCRA.get(code.trim().padStart(3, "0").slice(0, 3)) ?? null;
}

// Código de PSP del CVU (4 dígitos, posiciones 4 a 7).
export function bankByCvuPsp(code: string): BankEntity | null {
  return BY_PSP.get(code.trim().padStart(4, "0")) ?? null;
}

const fold = (s: string) =>
  s
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim();

const HAYSTACK = new Map(
  BANKS.map((b) => [
    b.slug,
    [b.name, b.shortName, b.slug, ...b.aliases].map(fold).join(" | "),
  ]),
);

// Búsqueda sin tildes ni mayúsculas sobre nombre, nombre corto, alias y slug.
// Consulta vacía → todo el catálogo.
export function searchBanks(query: string): BankEntity[] {
  const q = fold(query);
  if (!q) return [...BANKS];
  const terms = q.split(/\s+/);
  return BANKS.filter((b) => {
    const h = HAYSTACK.get(b.slug)!;
    return terms.every((t) => h.includes(t));
  });
}
